export function getProjectsWithDetails(): ProjectWithDetails[] {
  return PROJECTS.map((p) => {
    const construction = CONSTRUCTIONS.find((c) => c.project_id === p.id);
    const images = IMAGES.filter((img) => img.project_id === p.id);
    const profit = construction ? calcProfit(construction) : undefined;
    return { ...p, construction, images, profit };
  });
}

export function getProjectWithDetails(id: string): ProjectWithDetails | undefined {
  return getProjectsWithDetails().find((p) => p.id === id);
}

